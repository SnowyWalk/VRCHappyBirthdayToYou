import { test, expect } from "@playwright/test";
import { makeLink, nameField } from "./helpers";

test("system theme, manual override and reload persist across the editor and dialogs", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.emulateMedia({ colorScheme: "dark" });
  await page.goto("/");
  await expect(page.locator("html")).toHaveClass("dark");
  await page.getByRole("button", { name: "테마 전환", exact: true }).click();
  await expect(page.locator("html")).not.toHaveClass("dark");
  await page.reload();
  await expect(page.locator("html")).not.toHaveClass("dark");
  await page.getByRole("button", { name: "테마 전환", exact: true }).click();
  await page.emulateMedia({ colorScheme: "light" });
  await page.reload();
  await expect(page.locator("html")).toHaveClass("dark");
  await page.getByRole("button", { name: "불러오기", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog).toBeVisible();
  await expect(dialog).toHaveCSS("background-color", "rgb(21, 18, 27)");
  await page.keyboard.press("Escape");
  await nameField(page).fill("멜비");
  await makeLink(page);
  await expect(page.locator("html")).toHaveClass("dark");
  await page.screenshot({ path: "artifacts/screenshots/dark-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
  await page.screenshot({ path: "artifacts/screenshots/dark-mobile.png" });
  expect(errors).toEqual([]);
});
